const declarations = (properties: Record<string, string>, indent = "  ") =>
  Object.entries(properties)
    .map(([name, value]) => `${indent}--gw-${name}: ${value};`)
    .join("\n");

const colourProperties = (roles: Roles) =>
  Object.fromEntries(
    Object.entries(roles).map(([role, colour]) => [
      `color-${role}`,
      toCss(colour),
    ]),
  );

const modeBlock = (roles: Roles, dark: boolean, indent = "  ") =>
  [
    `${indent}color-scheme: ${dark ? "dark" : "light"};`,
    declarations({ ...colourProperties(roles), ...shadows(dark) }, indent),
  ].join("\n");

const themeCss = (theme: ResolvedTheme) => {
  const selector = `[data-gw-theme="${theme.id}"]`;
  const style = `${selector} {\n${declarations(styleProperties(theme.style))}\n}`;
  const { light, dark, darker } = theme.modes;
  const blocks = [style];

  if (light !== undefined) {
    blocks.push(`${selector} {\n${modeBlock(light, false)}\n}`);
  } else if (dark !== undefined) {
    blocks.push(`${selector} {\n${modeBlock(dark, true)}\n}`);
  }

  if (dark !== undefined) {
    blocks.push(
      `${selector}[data-gw-mode="dark"] {\n${modeBlock(dark, true)}\n}`,
    );

    if (light !== undefined) {
      blocks.push(
        `@media (prefers-color-scheme: dark) {\n  ${selector}:not([data-gw-mode]) {\n${modeBlock(dark, true, "    ")}\n  }\n}`,
      );
    }
  }

  if (darker !== undefined) {
    blocks.push(
      `${selector}[data-gw-mode="darker"] {\n${modeBlock(darker, true)}\n}`,
    );
  }

  return blocks.join("\n\n");
};

export const css = (themes: readonly ResolvedTheme[]) =>
  [
    `/* ${header} */`,
    `:root {\n${declarations(foundations)}\n}`,
    `@media (prefers-reduced-motion: reduce) {\n  :root {\n    --gw-motion-fast: 1ms;\n    --gw-motion-slow: 1ms;\n  }\n}`,
    ...themes.map(themeCss),
  ].join("\n\n") + "\n";

const hexRoles = (roles: Roles) =>
  Object.fromEntries(
    Object.entries(roles).map(([role, colour]) => [role, toHex(colour)]),
  );

const hexModes = (theme: ResolvedTheme) =>
  Object.fromEntries(
    modes.flatMap((mode) => {
      const roles = theme.modes[mode];

      return roles === undefined ? [] : [[mode, hexRoles(roles)]];
    }),
  );

const data = (themes: readonly ResolvedTheme[]) => ({
  themes: themes.map((theme) => ({
    id: theme.id,
    name: theme.name,
    description: theme.description,
    optional: theme.optional,
    family: theme.family ?? null,
    examples: theme.examples,
    style: theme.style,
    properties: styleProperties(theme.style),
    modes: hexModes(theme),
  })),
});

