const modeLabel: Record<Mode, string> = {
  light: "Light",
  dark: "Dark",
  darker: "Darker",
};

const roleLabel = (role: string) =>
  statuses.some((status) => status === role) ? `Status: ${role}` : role;

/** The contrast report as a docs page, one table per theme. */
export const contrastPage = (themes: readonly ResolvedTheme[]) => {
  const sections = themes.map((theme) => {
    const results = check(theme);

    const rows = [...new Set(results.map((result) => result.role))].map(
      (role) => {
        const cells = modes.map((mode) => {
          const result = results.find(
            (item: Check) => item.role === role && item.mode === mode,
          );

          return result === undefined
            ? "n/a"
            : `${result.ratio.toFixed(2)}${result.passes ? "" : " ✗"}`;
        });

        const target = results.find((item) => item.role === role)?.target ?? 0;

        return `| ${roleLabel(role)} | ${target} | ${cells.join(" | ")} |`;
      },
    );

    return [
      `## ${theme.name}`,
      "",
      theme.optional
        ? "Optional. Mapped from its own palette, so it's reported rather than held to the targets."
        : "",
      "",
      `| Role | Target | ${modes.map((mode) => modeLabel[mode]).join(" | ")} |`,
      "| --- | --- | --- | --- | --- |",
      ...rows,
    ]
      .filter((line, index, lines) => line !== "" || lines[index - 1] !== "")
      .join("\n");
  });

  return [
    "---",
    "title: Contrast report",
    "description: Every theme role measured against its contrast target on the raised surface, in light, dark and Darker.",
    "---",
    "",
    `<!-- ${header} -->`,
    "",
    "Each role is measured with the WCAG 2 ratio against the raised surface, the lowest-contrast surface text sits on. `mise run check` fails when a core theme misses a target; ✗ marks a miss.",
    "",
    ...sections.flatMap((section) => [section, ""]),
  ].join("\n");
};

