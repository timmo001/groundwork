/** One page for the optional themes, mapped from their own palettes. */
export const optionalPage = (themes: readonly ResolvedTheme[]) => {
  const optional = themes.filter((theme) => theme.optional);
  const families = [...new Set(optional.map((theme) => theme.family ?? ""))];

  return [
    "---",
    "title: Optional themes",
    "description: Catppuccin and Tokyo Night, mapped onto the roles so they stay faithful to their palettes. Apps opt in.",
    "---",
    "",
    `{/* ${header} */}`,
    "",
    "Each flavour is one mode of its palette, mapped straight onto the roles rather than solved, so it looks the way the palette's authors intended. They take Base's style. The [contrast report](/themes/contrast) shows where a palette sits below the core targets.",
    "",
    ...families.flatMap((family) => [
      `## ${family}`,
      "",
      ...optional
        .filter((theme) => theme.family === family)
        .flatMap((theme) => [
          `### ${theme.name}`,
          "",
          `<ThemePreview theme="${theme.id}" />`,
          "",
        ]),
    ]),
  ].join("\n");
};
