/**
 * Checks that every `define/` entry defines the `gw-` elements its element
 * renders, so an app that imports only some entries still gets each piece it
 * shows, and writes the "Built from" table on the components page from the
 * same reading. With `--check`, fails when an entry misses one or the table
 * is stale instead.
 */
import { readFile, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const check = process.argv.includes("--check");

const src = join(import.meta.dir, "..", "src");
const defineDir = join(src, "define");

const page = join(
  import.meta.dir,
  "..",
  "..",
  "..",
  "docs",
  "src",
  "content",
  "docs",
  "components",
  "index.mdx",
);

const start = "{/* Generated by `mise run gen` from the define/ entries. */}";
const end = "{/* End of the generated table. */}";

interface Entry {
  readonly file: string;
  readonly module: string;
  readonly tags: readonly string[];
  readonly imports: readonly string[];
}

const entries: Entry[] = await Promise.all(
  (await readdir(defineDir))
    .filter((name) => name.endsWith(".ts") && name !== "all.ts")
    .toSorted()
    .map(async (file) => {
      const text = await readFile(join(defineDir, file), "utf8");

      return {
        file,
        module: /from "\.\.\/([a-z-]+)\.js"/.exec(text)?.[1] ?? "",
        tags: [...text.matchAll(/\.define\("(gw-[a-z-]+)"\)/g)].flatMap(
          ([, tag]) => (tag === undefined ? [] : [tag]),
        ),
        imports: [...text.matchAll(/^import "\.\/([a-z-]+)\.js";/gm)].flatMap(
          ([, name]) => (name === undefined ? [] : [`${name}.ts`]),
        ),
      };
    }),
);

const entryOf = new Map(
  entries.flatMap((entry) => entry.tags.map((tag) => [tag, entry] as const)),
);

/** The `gw-` tags a module renders, with the helpers it builds them through. */
const rendered = async (module: string, seen = new Set<string>()) => {
  if (seen.has(module)) return new Set<string>();

  seen.add(module);

  const text = await readFile(join(src, `${module}.ts`), "utf8");

  const tags = new Set(
    [...text.matchAll(/\bh\(\s*"(gw-[a-z-]+)"/g)].flatMap(([, tag]) =>
      tag === undefined ? [] : [tag],
    ),
  );

  // Helpers such as dismiss.ts and field-info.ts render for the element, but
  // other elements' modules (gw-*.ts) are only imported for their types
  const helpers = [
    ...text.matchAll(/^import (?!type )[^;]*?from "\.\/([a-z-]+)\.js";/gms),
  ].flatMap(([, name]) =>
    name === undefined || name.startsWith("gw-") ? [] : [name],
  );

  for (const helper of helpers) {
    for (const tag of await rendered(helper, seen)) tags.add(tag);
  }

  return tags;
};

const problems: string[] = [];
const rows: [string, string[]][] = [];

for (const entry of entries) {
  const tags = await rendered(entry.module);

  for (const own of entry.tags) tags.delete(own);

  const needs = [...tags].toSorted((a, b) => a.localeCompare(b));

  for (const tag of needs) {
    const owner = entryOf.get(tag);

    if (owner === undefined) {
      problems.push(
        `${entry.file} renders ${tag}, which no define/ entry defines`,
      );
    } else if (!entry.imports.includes(owner.file)) {
      problems.push(
        `define/${entry.file} renders ${tag} but doesn't import ./${owner.file.replace(/\.ts$/, ".js")}`,
      );
    }
  }

  if (needs.length > 0) {
    for (const own of entry.tags) rows.push([own, needs]);
  }
}

if (problems.length > 0) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const table = [
  start,
  "",
  "| Element | Built from |",
  "| --- | --- |",
  ...rows
    .toSorted(([a], [b]) => a.localeCompare(b))
    .map(
      ([tag, needs]) =>
        `| \`${tag}\` | ${needs.map((need) => `\`${need}\``).join(", ")} |`,
    ),
  "",
  end,
].join("\n");

const text = await readFile(page, "utf8");
const from = text.indexOf(start);
const to = text.indexOf(end);

if (from === -1 || to === -1) {
  console.error(`${page} has no generated table markers`);
  process.exit(1);
}

const next = text.slice(0, from) + table + text.slice(to + end.length);

if (check) {
  if (next !== text) {
    console.error(
      "The components page's Built from table is stale; run `mise run gen` to update",
    );
    process.exit(1);
  }

  console.log("Every define/ entry defines what its element renders");
} else {
  await writeFile(page, next);
}
