/**
 * Writes `custom-elements.json`, the Custom Elements Manifest, from the
 * elements' class docstrings, and `src/events.ts`, the typed event map `on()`
 * reads, from their `@fires` tags. With `--check`, fails when either
 * committed file is stale instead. Editors, `lit-analyzer` and framework
 * wrappers read the manifest.
 */
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";

interface ManifestEvent {
  readonly name: string;
  readonly type?: { readonly text: string };
}

interface ManifestDeclaration {
  readonly tagName?: string;
  readonly events?: readonly ManifestEvent[];
}

interface Manifest {
  readonly modules: readonly {
    readonly declarations?: readonly ManifestDeclaration[];
  }[];
}

const check = process.argv.includes("--check");

// The analyzer resolves --outdir against the working directory, absolute or not
const outdir = check ? ".manifest-check" : ".";

if (check) await mkdir(outdir, { recursive: true });

const analyzer = Bun.spawn(
  ["cem", "analyze", "--quiet", "--globs", "src/**/*.ts", "--outdir", outdir],
  { stdout: "inherit", stderr: "inherit" },
);

if ((await analyzer.exited) !== 0) process.exit(1);

const manifestText = await readFile(
  join(outdir, "custom-elements.json"),
  "utf8",
);

const manifest: Manifest = JSON.parse(manifestText);

const entries = manifest.modules
  .flatMap((module) => module.declarations ?? [])
  .flatMap(({ tagName, events }) =>
    tagName === undefined || events === undefined || events.length === 0
      ? []
      : [{ tagName, events }],
  )
  .toSorted((a, b) => a.tagName.localeCompare(b.tagName));

const eventMap = [
  "// Generated by `mise run gen` from the elements' `@fires` docstrings. Don't edit.",
  "",
  "/** The events each `gw-` element fires, by tag. `on()` reads it. */",
  "export interface GwEventMap {",
  ...entries.flatMap(({ tagName, events }) => [
    `  "${tagName}": {`,
    ...events.map(
      (event) => `    ${event.name}: ${event.type?.text ?? "Event"};`,
    ),
    "  };",
  ]),
  "}",
  "",
].join("\n");

if (check) {
  await rm(outdir, { recursive: true });

  const stale = [
    manifestText === (await readFile("custom-elements.json", "utf8"))
      ? []
      : ["custom-elements.json"],
    eventMap === (await readFile("src/events.ts", "utf8"))
      ? []
      : ["src/events.ts"],
  ].flat();

  if (stale.length > 0) {
    console.error(
      `${stale.join(" and ")} stale; run \`mise run gen\` to update`,
    );
    process.exit(1);
  }

  console.log("Custom Elements Manifest and event map are up to date");
} else {
  await writeFile("src/events.ts", eventMap);
}
